def type_of(name):
    if name.endswith("街道") or name.endswith("区"):
        return "street"
    if name.endswith("乡"):
        return "xian"
    return "town"


def build_reason(county, name, cat):
    info = COUNTY[county]
    sp = SPECIAL[county].get(name)
    parts = [info["bg"]]
    if sp:
        parts.append(sp[1] + "；")
    else:
        t = type_of(name)
        base = TYPE_TEXT[t]
        if county in AUTONOMOUS:
            base = ("黎苗山地原乡，部落人情网络、头人与教会组织牢固；"
                    if t != "street" else
                    "县城职能片区，公教与商贾聚居；")
        parts.append(base)
    parts.append("综合研判：" + CAT_TEXT[cat])
    return "".join(parts)


